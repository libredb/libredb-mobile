/**
 * Writes the governance source of the `governed` profile of tool/studio-dev/docker-compose.yml. NOT FOR PRODUCTION.
 *
 *   bun tool/studio-dev/governed/generate.ts ../libredb-studio
 *
 * The argument is a checkout of libredb/libredb-studio. The script builds the bridge schema from that checkout's
 * published manifest with Studio's own fixture builder, seals the connection credentials with Studio's own test
 * sealer (docs/GOVERNANCE.md in Studio), and writes three files next to itself:
 *
 * - governance-source.sql: the bridge schema and its rows, the init script of the governance-source service.
 * - governed-db.sql: Studio's storage database and the sales database the governed connections open.
 * - keyring.json: Studio's private key, which opens the sealed credentials.
 *
 * Every key, password and ephemeral key is derived from a fixed label, so a second run writes the same bytes. They
 * protect nothing and are committed on purpose, like the passwords in docker-compose.yml.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const studio = process.argv[2];
if (studio === undefined) {
  throw new Error("Usage: bun tool/studio-dev/governed/generate.ts <libredb-studio checkout>");
}
const studioRoot = path.resolve(studio);
const helper = (name: string) => path.join(studioRoot, "tests/helpers/governance", name);

const { buildFixtureDdl, readFixtureManifest } = await import(helper("fixture-ddl.ts"));
const { testKey } = await import(helper("keyring-file.ts"));
const { sealSecret } = await import(helper("lsb1-seal.ts"));

const derived = (label: string): Buffer =>
  createHash("sha256").update(`libredb-mobile studio-dev governed: ${label}`, "utf8").digest();

const manifest = readFixtureManifest();
const key = testKey(derived("studio private key"));
const studioRevision = execFileSync("git", ["-C", studioRoot, "rev-parse", "--short=9", "HEAD"], { encoding: "utf8" })
  .trim();

/** The Keycloak user ids of tool/studio-dev/docker-compose.yml, which are the `sub` a grant names. */
const SUBJECTS = { admin: "a0000000-0000-4000-8000-000000000001", user: "a0000000-0000-4000-8000-000000000002" };

const STUDIO_PASSWORD = "00112233445566778899aabbccddeeff";
const STORAGE_PASSWORD = "studio-dev-storage-not-for-production";
const READ = { user: "sales_reader", password: "sales-reader-not-for-production" };
const WRITE = { user: "sales_writer", password: "sales-writer-not-for-production" };

const DEFINITION = { host: "governed-db", port: 5432, database: "sales", ssl: { mode: "disable" } };
const CONNECTIONS = [
  { id: "sales-dev", name: "Sales (development)", environment: "development", group: "Sales", color: "#16a34a" },
  { id: "sales-prod", name: "Sales (production)", environment: "production", group: "Sales", color: "#dc2626" },
];
const GRANTS = [
  { subject: SUBJECTS.admin, connection: "sales-dev", level: "write" },
  { subject: SUBJECTS.admin, connection: "sales-prod", level: "write" },
  { subject: SUBJECTS.user, connection: "sales-dev", level: "write" },
  { subject: SUBJECTS.user, connection: "sales-prod", level: "read" },
];
const CANARY_BINDING = { connectionId: "canary", level: "read", engine: "canary", definition: {} };

const literal = (value: string): string => `'${value.replaceAll("'", "''")}'`;
const seal = (connectionId: string, level: "read" | "write", secret: Record<string, string>): string =>
  sealSecret(
    key.publicKey,
    { connectionId, level, engine: "postgres", definition: DEFINITION },
    secret,
    derived(`ephemeral ${connectionId} ${level}`),
  );

const header = (purpose: string): string[] => [
  `-- ${purpose}`,
  "-- Generated by tool/studio-dev/governed/generate.ts from libredb-studio " +
    `${studioRevision}; do not edit by hand. NOT FOR PRODUCTION.`,
  "",
];

const ddl = buildFixtureDdl(manifest, { studioPassword: STUDIO_PASSWORD });
const schema = `"${manifest.schema}"`;
const source = [
  ...header("The governance source of the governed profile: the bridge schema, its roles and its rows."),
  ...[...ddl.roles, ...ddl.objects].map((statement: string) => `${statement};`),
  "",
  `INSERT INTO ${schema}.contract_source (version, status, sunset_after, notify_channel) VALUES (${manifest.contractVersion}, 'current', NULL, ${literal(manifest.notification.channel)});`,
  `INSERT INTO ${schema}.seal_canary_v1_source (kid, envelope, created_at) VALUES (${literal(key.kid)}, ${literal(sealSecret(key.publicKey, CANARY_BINDING, { user: "libredb-canary" }, derived("ephemeral canary")))}, now());`,
  ...CONNECTIONS.map(
    (c) =>
      `INSERT INTO ${schema}.connections_v1_source (connection_id, name, engine, environment, group_name, color, definition, read_secret, write_secret, mcp_enabled, updated_at) VALUES (${literal(c.id)}, ${literal(c.name)}, 'postgres', ${literal(c.environment)}, ${literal(c.group)}, ${literal(c.color)}, ${literal(JSON.stringify(DEFINITION))}, ${literal(seal(c.id, "read", READ))}, ${literal(seal(c.id, "write", WRITE))}, false, now());`,
  ),
  ...GRANTS.map(
    (g) =>
      `INSERT INTO ${schema}.grants_v1_source (subject, connection_id, level, expires_at, downgraded, granted_at) VALUES (${literal(g.subject)}, ${literal(g.connection)}, ${literal(g.level)}, NULL, false, now());`,
  ),
  `INSERT INTO ${schema}.settings_v1_source (key, value, updated_at) VALUES ('queryLog.statementCapture', '"full"', now());`,
  "",
];

const governedDb = [
  ...header("Studio's storage and the sales database the governed connections open."),
  `CREATE ROLE studio LOGIN PASSWORD ${literal(STORAGE_PASSWORD)};`,
  "CREATE DATABASE studio OWNER studio;",
  `CREATE ROLE ${READ.user} LOGIN PASSWORD ${literal(READ.password)};`,
  `CREATE ROLE ${WRITE.user} LOGIN PASSWORD ${literal(WRITE.password)};`,
  "CREATE DATABASE sales;",
  "\\connect studio",
  "CREATE SCHEMA studio AUTHORIZATION studio;",
  "\\connect sales",
  "REVOKE ALL ON SCHEMA public FROM PUBLIC;",
  `GRANT USAGE ON SCHEMA public TO ${READ.user}, ${WRITE.user};`,
  "CREATE TABLE public.orders (id integer PRIMARY KEY, customer text NOT NULL, total numeric(10, 2) NOT NULL);",
  "INSERT INTO public.orders VALUES (1, 'Ada', 120.50), (2, 'Grace', 75.00), (3, 'Linus', 9.99);",
  `GRANT SELECT ON public.orders TO ${READ.user};`,
  `GRANT SELECT, INSERT, UPDATE, DELETE ON public.orders TO ${WRITE.user};`,
  "",
];

const here = import.meta.dir;
writeFileSync(path.join(here, "governance-source.sql"), source.join("\n"));
writeFileSync(path.join(here, "governed-db.sql"), governedDb.join("\n"));
writeFileSync(path.join(here, "keyring.json"), `${JSON.stringify({ version: 1, keys: [key.text] })}\n`);
console.log(`Wrote the governed profile for key ${key.kid} from libredb-studio ${studioRevision}.`);
