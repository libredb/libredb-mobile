const _shareChannel = MethodChannel('dev.fluttercommunity.plus/share');
const _pathProviderChannel = MethodChannel('plugins.flutter.io/path_provider');

/// The sentence Studio's route bound sets (`sourceBoundTruncationReason`, libredb-studio
/// `src/lib/db/object-kinds.ts:643-645`).
const _routeBound = 'the source read was bounded at 1,000,000 characters by its caller';

Widget _app(ObjectSource source, {ScreenCaptureProtection? protection}) => withScreenCaptureProtection(
  protection: protection,
  MaterialApp(
    localizationsDelegates: const [
      S.delegate,
      GlobalMaterialLocalizations.delegate,
      GlobalWidgetsLocalizations.delegate,
      GlobalCupertinoLocalizations.delegate,
    ],
    supportedLocales: S.delegate.supportedLocales,
    home: Scaffold(body: ObjectSourceView(source: source)),
  ),
);

ObjectSource _one(SourcePart part) => ObjectSource(path: const ['sales', 'order_totals'], kind: 'view', parts: [part]);

SourceText _text(String text, {String language = 'sql', SourceTruncation? truncated}) => SourceText(
  id: 'definition',
  label: 'Definition',
  text: text,
  language: language,
  origin: SourceOrigin.stored,
  truncated: truncated,
);

/// The span of [text] in the source lines on screen.
TextSpan? _span(WidgetTester tester, String text) {
  for (final rich in tester.widgetList<RichText>(find.byType(RichText))) {
    TextSpan? found;
    rich.text.visitChildren((span) {
      if (span is TextSpan && span.text == text) {
        found = span;
        return false;
      }
      return true;
    });
    if (found != null) return found;
  }
  return null;
}

void main() {
  late List<MethodCall> platformCalls;
  late List<MethodCall> shareCalls;
  late Object? Function(MethodCall call) answerShare;

  setUp(() {
    platformCalls = [];
    shareCalls = [];
    answerShare = (_) => 'dev.fluttercommunity.plus/share/success';
    final messenger = TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    messenger.setMockMethodCallHandler(SystemChannels.platform, (call) async {
      platformCalls.add(call);
      return null;
    });
    messenger.setMockMethodCallHandler(_shareChannel, (call) async {
      shareCalls.add(call);
      return answerShare(call);
    });
  });

  tearDown(() {
    final messenger = TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    messenger.setMockMethodCallHandler(SystemChannels.platform, null);
    messenger.setMockMethodCallHandler(_shareChannel, null);
    messenger.setMockMethodCallHandler(_pathProviderChannel, null);
  });

  group('recorded Postgres answers (#49)', () {
    testWidgets('the view renders with SQL highlighting, line numbers and its captions', (tester) async {
      await tester.pumpWidget(_app(sourceAnswer('source_postgres_view')));

      final theme = Theme.of(tester.element(find.byType(ObjectSourceView)));
      expect(_span(tester, 'SELECT')?.style?.color, theme.colorScheme.primary);
      expect(_span(tester, 'JOIN')?.style?.color, theme.colorScheme.primary);
      expect(_span(tester, 'order_items'), isNull, reason: 'a name is part of a plain span, not a keyword');
      expect(find.text('1'), findsOneWidget);
      expect(find.text('8'), findsOneWidget);
      expect(find.text('Regenerated by Studio, not the stored text'), findsOneWidget);
      expect(find.text('Partial'), findsOneWidget);
      expect(find.textContaining('Truncated'), findsNothing);
      expect(find.byType(SegmentedButton<int>), findsNothing, reason: 'one part needs no switch');
    });

    testWidgets('the function renders with highlighting and is not partial', (tester) async {
      await tester.pumpWidget(_app(sourceAnswer('source_postgres_function')));

      final theme = Theme.of(tester.element(find.byType(ObjectSourceView)));
      expect(_span(tester, 'CREATE')?.style?.color, theme.colorScheme.primary);
      expect(_span(tester, 'RETURNS')?.style?.color, theme.colorScheme.primary);
      expect(find.text('Regenerated by Studio, not the stored text'), findsOneWidget);
      expect(find.text('Partial'), findsNothing);
    });
  });

  testWidgets('the source holds one capture lease while on screen and releases it when it leaves', (tester) async {
    final protection = recordingScreenCaptureProtection();
    await tester.pumpWidget(_app(_one(_text('SELECT 1')), protection: protection));
    expect(protection.leases, 1);

    await tester.pumpWidget(withScreenCaptureProtection(protection: protection, const SizedBox()));
    expect(protection.leases, 0);
  });

  testWidgets('stored text has no regenerated caption', (tester) async {
    await tester.pumpWidget(_app(_one(_text('SELECT 1'))));

    expect(find.text('Regenerated by Studio, not the stored text'), findsNothing);
    expect(find.text('Partial'), findsNothing);
  });

  testWidgets('a package switches between its specification and its body (#48)', (tester) async {
    await tester.pumpWidget(_app(sourceAnswer('handwritten/oracle/source_package')));

    expect(find.byType(SegmentedButton<int>), findsOneWidget);
    expect(find.text('Package specification'), findsOneWidget);
    expect(find.textContaining('PACKAGE BODY', findRichText: true), findsNothing);
    expect(find.textContaining('FUNCTION total(p NUMBER) RETURN NUMBER;', findRichText: true), findsOneWidget);

    await tester.tap(find.text('Package body'));
    await tester.pumpAndSettle();

    expect(find.textContaining('PACKAGE BODY', findRichText: true), findsOneWidget);
    expect(find.textContaining('RETURN NUMBER;', findRichText: true), findsNothing);
  });

  group('truncation', () {
    testWidgets(
      'a Firestore subcollection list reads Studio\'s sentence about collection ids, with no unit of its own',
      (tester) async {
        await tester.pumpWidget(_app(sourceAnswer('handwritten/firestore/source_document')));
        await tester.tap(find.text('Subcollections'));
        await tester.pumpAndSettle();

        expect(find.text('Truncated: Studio stopped listing collection ids after 10 requests'), findsOneWidget);
        expect(find.textContaining('characters'), findsNothing);
        expect(
          find.textContaining(RegExp(r'Truncated.*\b20\b')),
          findsNothing,
          reason: 'the limit is never shown without its unit',
        );
      },
    );

    testWidgets('a part cut at the route\'s bound reads the route\'s sentence', (tester) async {
      await tester.pumpWidget(
        _app(_one(_text('SELECT 1', truncated: const SourceTruncation(limit: 1000000, reason: _routeBound)))),
      );

      expect(find.text('Truncated: $_routeBound'), findsOneWidget);
    });
  });

  group('parts that hold no text', () {
    testWidgets('a neutral statement reads as a fact (#48)', (tester) async {
      await tester.pumpWidget(_app(sourceAnswer('handwritten/firestore/source_document_colon_id')));
      await tester.tap(find.text('Subcollections'));
      await tester.pumpAndSettle();

      expect(find.textContaining('Studio cannot list the subcollections of a document'), findsOneWidget);
      expect(find.text('This definition could not be read'), findsNothing);
      expect(find.byTooltip('Copy all'), findsNothing);
      expect(find.byTooltip('Share'), findsNothing);
    });

    testWidgets('a refusal reads as a refusal', (tester) async {
      await tester.pumpWidget(
        _app(_one(const SourceUnavailable(id: 'comment', label: 'Comment', reason: 'no comment is set'))),
      );

      expect(find.text('This definition could not be read'), findsOneWidget);
      expect(find.text('no comment is set'), findsOneWidget);
      expect(find.byTooltip('Copy all'), findsNothing);
    });
  });

  testWidgets('Copy all puts the whole text of the shown part on the clipboard', (tester) async {
    final source = sourceAnswer('handwritten/oracle/source_package');
    await tester.pumpWidget(_app(source));
    await tester.tap(find.text('Package body'));
    await tester.pumpAndSettle();

    await tester.tap(find.byTooltip('Copy all'));
    await tester.pump();

    final copy = platformCalls.singleWhere((call) => call.method == 'Clipboard.setData');
    expect((copy.arguments as Map)['text'], (source.parts.last as SourceText).text);
    expect(find.text('Copied'), findsOneWidget);
  });

  testWidgets('shows a copy that fails, with its error code', (tester) async {
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger.setMockMethodCallHandler(
      SystemChannels.platform,
      (call) async => call.method == 'Clipboard.setData' ? throw PlatformException(code: 'clipboard_denied') : null,
    );
    await tester.pumpWidget(_app(_one(_text('SELECT 1'))));

    await tester.tap(find.byTooltip('Copy all'));
    await tester.pump();

    expect(find.text('Could not copy (clipboard_denied)'), findsOneWidget);
    expect(find.text('Copied'), findsNothing);
  });

  testWidgets('splits lines on CRLF as well as LF, and shows no carriage return', (tester) async {
    await tester.pumpWidget(_app(_one(_text('SELECT 1\r\nFROM t\nWHERE x'))));

    expect(find.text('3'), findsOneWidget);
    for (final rich in tester.widgetList<RichText>(find.byType(RichText))) {
      expect(rich.text.toPlainText(), isNot(contains('\r')));
    }
    expect(_span(tester, 'FROM'), isNotNull);
  });

  group('Share', () {
    testWidgets('sends a part of up to 100,000 characters as text', (tester) async {
      final text = 'x' * 100000;
      await tester.pumpWidget(_app(_one(_text(text))));

      await tester.tap(find.byTooltip('Share'));
      await tester.pump();

      final share = shareCalls.single;
      expect(share.method, 'share');
      expect((share.arguments as Map)['text'], text);
      expect((share.arguments as Map).containsKey('paths'), isFalse);
    });

    testWidgets('sends a longer part as a UTF-8 file named after the object and the part', (tester) async {
      final temp = Directory.systemTemp.createTempSync('source_share');
      addTearDown(() => temp.deleteSync(recursive: true));
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger.setMockMethodCallHandler(
        _pathProviderChannel,
        (call) async => temp.path,
      );
      final text = 'İ${'x' * 100000}';
      await tester.pumpWidget(_app(_one(_text(text))));

      await tester.runAsync(() async {
        await tester.tap(find.byTooltip('Share'));
        while (shareCalls.isEmpty) {
          await Future<void>.delayed(const Duration(milliseconds: 10));
        }
      });

      final arguments = shareCalls.single.arguments as Map;
      expect(arguments.containsKey('text'), isFalse);
      final path = (arguments['paths'] as List).single as String;
      expect(path, endsWith('/order_totals-definition.sql'));
      expect(File(path).readAsStringSync(), text);
    });

    testWidgets('names a file of text that is not SQL .txt', (tester) async {
      final temp = Directory.systemTemp.createTempSync('source_share');
      addTearDown(() => temp.deleteSync(recursive: true));
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger.setMockMethodCallHandler(
        _pathProviderChannel,
        (call) async => temp.path,
      );
      await tester.pumpWidget(
        _app(
          ObjectSource(
            path: const ['customers/alice'],
            kind: 'document',
            parts: [
              SourceText(
                id: 'data',
                label: 'Data',
                text: '1' * 100001,
                language: 'json',
                origin: SourceOrigin.rendered,
              ),
            ],
          ),
        ),
      );

      await tester.runAsync(() async {
        await tester.tap(find.byTooltip('Share'));
        while (shareCalls.isEmpty) {
          await Future<void>.delayed(const Duration(milliseconds: 10));
        }
      });

      final path = ((shareCalls.single.arguments as Map)['paths'] as List).single as String;
      expect(path, endsWith('/customers_alice-data.txt'));
    });

    testWidgets('shows a share that fails, with its error code', (tester) async {
      answerShare = (_) => throw PlatformException(code: 'share_busy');
      await tester.pumpWidget(_app(_one(_text('SELECT 1'))));

      await tester.tap(find.byTooltip('Share'));
      await tester.pump();

      expect(find.text('Could not share (share_busy)'), findsOneWidget);
    });
  });

  group('a part of a million characters', () {
    String sql(int characters) {
      const line = 'SELECT id, name, total FROM sales.orders WHERE total > 100; -- line\n';
      final buffer = StringBuffer();
      while (buffer.length + line.length <= characters) {
        buffer.write(line);
      }
      buffer.write('x' * (characters - buffer.length));
      return buffer.toString();
    }

    testWidgets('opens in under a second, builds only the lines on screen and scrolls to its end', (tester) async {
      final text = sql(1000000);
      expect(text.length, 1000000);
      final source = _one(_text(text, truncated: const SourceTruncation(limit: 1000000, reason: _routeBound)));
      // The first frame of a test also loads fonts and builds the app, which says nothing about the part.
      await tester.pumpWidget(_app(_one(const SourceStatement(id: 's', label: 'S', statement: 'warm up'))));

      final watch = Stopwatch()..start();
      await tester.pumpWidget(_app(source));
      watch.stop();

      expect(watch.elapsed, lessThan(const Duration(seconds: 1)));
      expect(find.text('Truncated: $_routeBound'), findsOneWidget);
      expect(find.text('1'), findsOneWidget);
      expect(
        find.textContaining('FROM sales.orders', findRichText: true).evaluate().length,
        lessThan(100),
        reason: 'only the lines on screen are built, never one text of the whole part',
      );

      final lines = '\n'.allMatches(text).length + 1;
      await tester.scrollUntilVisible(
        find.text('$lines'),
        5000,
        maxScrolls: 100,
        scrollable: find.descendant(of: find.byType(ListView), matching: find.byType(Scrollable)),
      );
      expect(find.text('$lines'), findsOneWidget);
    });

    testWidgets('a single line of a million characters is cut into rows, so no row holds it whole', (tester) async {
      final text = 'a' * 1000000;
      await tester.pumpWidget(_app(_one(const SourceStatement(id: 's', label: 'S', statement: 'warm up'))));
      final watch = Stopwatch()..start();
      await tester.pumpWidget(_app(_one(_text(text, language: 'plaintext'))));
      watch.stop();

      expect(watch.elapsed, lessThan(const Duration(seconds: 1)));
      for (final rich in tester.widgetList<RichText>(find.byType(RichText))) {
        expect(rich.text.toPlainText().length, lessThanOrEqualTo(ObjectSourceView.maxRowLength));
      }
      expect(find.text('1'), findsOneWidget);
      expect(find.text('2'), findsNothing, reason: 'the rows of one line share its number');
    });
  });
}
