import 'package:libredb_mobile/features/platform_audit/domain/entities/audit_event.dart';

/// A governed query event of test data, every field set unless a test overrides it.
AuditEvent auditEvent(
  String id, {
  DateTime? startedAt,
  DateTime? finishedAt,
  String subject = '5f0c1a52-1d2e-4c1b-9a51-000000000001',
  String? username = 'alice.reader',
  String? sessionRole = 'user',
  String connectionId = 'cm0conn0000000000000000001',
  bool? connectionKnown = true,
  String connectionName = 'Orders',
  String? engine = 'postgres',
  String? accessLevel = 'read',
  String source = 'editor',
  String statementType = 'SELECT',
  String? explain,
  String statementCapture = 'full',
  String? statement = 'SELECT id FROM orders\nWHERE id = 1',
  bool statementTruncated = false,
  int? rowCount = 1,
  int durationMs = 44,
  String status = 'success',
  String? errorCode,
  String? errorMessage,
  String? transactionOutcome,
}) => AuditEvent(
  eventId: id,
  startedAt: startedAt ?? DateTime.utc(2026, 10, 25, 9, 42, 10),
  finishedAt: finishedAt ?? DateTime.utc(2026, 10, 25, 9, 42, 11),
  subject: subject,
  username: username,
  sessionRole: sessionRole,
  connectionId: connectionId,
  connectionKnown: connectionKnown,
  connectionName: connectionName,
  engine: engine,
  accessLevel: accessLevel,
  source: source,
  statementType: statementType,
  explain: explain,
  statementCapture: statementCapture,
  statement: statement,
  statementTruncated: statementTruncated,
  rowCount: rowCount,
  durationMs: durationMs,
  status: status,
  errorCode: errorCode,
  errorMessage: errorMessage,
  transactionOutcome: transactionOutcome,
);
